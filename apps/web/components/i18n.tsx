export type TranslationKey = keyof typeof messages["zh-Hant"];
type Values = Record<string, string | number>;

function localeTag(locale: AppLocale): string {
  return locale === "zh-Hant" ? "zh-TW" : "en-US";
}

function interpolate(message: string, values?: Values): string {
  return message.replace(/\{(\w+)\}/g, (_, key: string) => String(values?.[key] ?? `{${key}}`));
}

type I18nValue = {
  locale: AppLocale;
  localeTag: string;
  setLocale: (locale: AppLocale) => void;
  t: (key: TranslationKey, values?: Values) => string;
  number: (value: number, options?: Intl.NumberFormatOptions) => string;
  time: (value: number | Date) => string;
  dateTime: (value: number | Date) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<AppLocale>(DEFAULT_LOCALE);
  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && APP_LOCALES.includes(saved as AppLocale)) setLocaleState(saved as AppLocale);
  }, []);
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const setLocale = useCallback((next: AppLocale) => {
    setLocaleState(next);
    localStorage.setItem(STORAGE_KEY, next);
  }, []);
  const tag = localeTag(locale);
  const value = useMemo<I18nValue>(() => ({
    locale,
    localeTag: tag,
    setLocale,
    t: (key, values) => interpolate(messages[locale][key], values),
    number: (number, options) => new Intl.NumberFormat(tag, options).format(number),
    time: (value) => new Date(value).toLocaleTimeString(tag),
    dateTime: (value) => new Date(value).toLocaleString(tag),
  }), [locale, setLocale, tag]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used within I18nProvider");
  return value;
}

export function LanguageSwitcher() {
  const { locale, setLocale, t } = useI18n();
  return <label className="language-switcher"><span>{t("language.label")}</span><select value={locale} onChange={(event) => setLocale(event.target.value as AppLocale)} aria-label={t("language.label")}>
    <option value="zh-Hant">{t("language.zhHant")}</option>
    <option value="en">{t("language.en")}</option>
  </select></label>;
}
